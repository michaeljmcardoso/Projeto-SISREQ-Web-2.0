import streamlit as st

def pagina_sobre_regularizacao_quilombola():
    st.subheader("Sobre a Regularização Quilombola")
    st.write("""
        😊 A regularização fundiária quilombola é um processo que garante o direito à terra para as comunidades. Em resumo, funciona assim:

       📜 Reconhecimento da Comunidade: Primeiro, a própria comunidade se autoidentifica como quilombola e é certificada pela Fundação Cultural Palmares (FCP).
             
       🗺️ Estudo do Território (RTID): Em seguida, o INCRA realiza um estudo aprofundado (o Relatório Técnico de Identificação e Delimitação - RTID) para entender a história, cultura e delimitar a área tradicionalmente ocupada. 
             
       ✅ Reconhecimento Oficial: Com o RTID aprovado, o INCRA publica uma Portaria de Reconhecimento, oficializando o território. 
             
       ✍️ Declaração de Interesse Social: O Presidente da República assina um Decreto declarando a área como de interesse social para fins de desapropriação, se houver terras particulares dentro do território. 
             
       🏡 Titulação: Por último, o título de propriedade da terra é emitido e registrado em nome da comunidade, garantindo a posse coletiva e permanente do território. 
             
        É um caminho que busca assegurar o direito ancestral dessas comunidades! ✨.
    """)